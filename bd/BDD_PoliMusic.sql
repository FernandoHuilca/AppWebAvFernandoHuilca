-- For login usr_polimusic, create a user in the database
IF NOT EXISTS (SELECT 1 FROM sys.database_principals WHERE name = 'usr_polimusic')
BEGIN
-- For login login_name, create a user in the database
    CREATE USER usr_polimusic FOR LOGIN usr_polimusic WITH DEFAULT_SCHEMA = [dbo];
    PRINT 'User created successfully.';
END
ELSE
BEGIN
    PRINT 'User usr_polimusic already exists.';
END
GO

-- Add user to the database owner role
IF NOT EXISTS (
    SELECT 1 FROM sys.database_role_members
    WHERE member_principal_id = ( SELECT principal_id FROM sys.database_principals WHERE name = N'usr_polimusic' )
    AND role_principal_id = ( SELECT principal_id FROM sys.database_principals WHERE name = N'db_owner' )
)
BEGIN
    EXEC sp_addrolemember N'db_owner', N'usr_polimusic';
	PRINT 'User usr_polimusic added to db_owner role successfully.';
END
ELSE
BEGIN
    PRINT 'User usr_polimusic is already a member of db_owner role.';
END
GO

