BEGIN
	-- IMPORTANTE: usa TU contraseña propias antes de ejecutar (no la dejes publica en git).
	CREATE LOGIN  [usr_polimusic] WITH PASSWORD = 'PON_TU_CONTRASENA_AQUI';
    PRINT 'Login "usr_polimusic" created successfully.';
END
ELSE
BEGIN
    PRINT 'Login "usr_polimusic" already exists.';
END;
GO

